// Builds the Obsidian plugin into obsidian/dist/: main.js (the plugin, with renderer/, panzoom, ELK and the catalog of
// types bundled; `obsidian` is Obsidian's own), styles.css (renderer/style.css scoped under .maps-md, then the layer
// of the plugin, obsidian/styles.css) and manifest.json. Run: npm run build:obsidian. Copy the three files into
// <vault>/.obsidian/plugins/maps-md/ to try it.

import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build, type Plugin } from 'esbuild';
import { scopeCss } from './scope-css.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const dist = join(here, 'dist');

/** The catalog of types of the skill, as the module `maps-md:catalog`: each type with its definition, layout, style. */
export const catalogPlugin: Plugin = {
  name: 'maps-md-catalog',
  setup(b) {
    b.onResolve({ filter: /^maps-md:catalog$/ }, () => ({ path: 'catalog', namespace: 'maps-md' }));
    b.onLoad({ filter: /.*/, namespace: 'maps-md' }, () => {
      const dir = join(root, 'skills', 'maps', 'types');
      const read = (name: string) => (existsSync(join(dir, name)) ? readFileSync(join(dir, name), 'utf8') : undefined);
      const types: Record<string, { md: string; layout?: string; css?: string }> = {};
      for (const name of readdirSync(dir).filter((n) => n.endsWith('.md') && !n.endsWith('.layout.md'))) {
        const type = name.slice(0, -3);
        types[type] = { md: read(name)!, layout: read(`${type}.layout.md`), css: read(`${type}.css`) };
      }
      return { contents: JSON.stringify(types), loader: 'json', watchFiles: readdirSync(dir).map((n) => join(dir, n)) };
    });
  },
};

/** The styles of the plugin: the page's, scoped, then the plugin's own layer. */
export function pluginCss() {
  const page = scopeCss(readFileSync(join(root, 'renderer', 'style.css'), 'utf8'), {
    scope: '.maps-md',
    dark: '.theme-dark',
    rename: { '#page': '#maps-md-page', '.canvas': '.maps-canvas' },
  });
  return `/* maps.md for Obsidian: generated by obsidian/build.ts from renderer/style.css (scoped under .maps-md) and obsidian/styles.css. Do not edit. */\n${page}\n\n${readFileSync(join(here, 'styles.css'), 'utf8')}`;
}

/** The notices of what main.js bundles, which their licenses ask to keep with every copy. */
function notices(inputs: string[]) {
  const packages = new Map<string, string[]>();
  for (const input of inputs) {
    const m = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
    if (m) packages.set(m[1], [...(packages.get(m[1]) ?? []), input]);
  }
  const texts: string[] = [];
  const lines = [...packages.keys()].sort().map((name) => {
    const dir = join(root, 'node_modules', name);
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const file = readdirSync(dir).find((n) => /licen[cs]e/i.test(n));
    const text = file ? readFileSync(join(dir, file), 'utf8').trim() : '';
    if (!text) throw new Error(`No license file in ${name}: add its notice by hand.`);
    texts.push(`The license of ${name}:\n\n${text}`);
    return `${name} ${pkg.version}, ${pkg.license}. Source: ${String(pkg.repository?.url ?? pkg.repository ?? '').replace(/^git\+/, '')}`;
  });
  return `/*! maps.md for Obsidian, MIT license. Copyright (c) 2026 Florent Brimeux. https://github.com/florentbx/maps.md\n\nIt bundles:\n${lines.join('\n')}\n\n${texts.join('\n\n').replace(/\*\//g, '* /')}\n*/`;
}

/** The plugin, bundled: `obsidian` and what Obsidian provides are left out. */
export async function bundle(entry: string, outfile: string, options: { external?: string[]; alias?: Record<string, string>; format?: 'cjs' | 'iife' } = {}) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: options.format ?? 'cjs',
    platform: 'browser',
    target: 'es2020',
    outfile,
    external: options.external ?? ['obsidian', 'electron', '@codemirror/*', '@lezer/*'],
    alias: options.alias,
    plugins: [catalogPlugin],
    legalComments: 'none',
    minify: true,
    treeShaking: true,
    tsconfigRaw: '{}',
    metafile: true,
    write: false,
  });
  const js = result.outputFiles[0].text;
  writeFileSync(outfile, `${notices(Object.keys(result.metafile.inputs))}\n${js}`);
}

async function main() {
  mkdirSync(dist, { recursive: true });
  await bundle(join(here, 'main.ts'), join(dist, 'main.js'));
  writeFileSync(join(dist, 'styles.css'), pluginCss());
  copyFileSync(join(here, 'manifest.json'), join(dist, 'manifest.json'));
  const size = (name: string) => `${Math.round(readFileSync(join(dist, name)).length / 1024)} KB`;
  console.log(`obsidian/dist/: main.js (${size('main.js')}), styles.css (${size('styles.css')}), manifest.json.`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
